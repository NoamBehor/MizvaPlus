const MODULE_ID = 'cycle-30-v1';

function lesson(
  sequence: number,
  type: DailyLearningContent['type'],
  topicHebrew: string,
  bodyHebrew: string,
  sourceTitle: string,
  sourceReference: string,
  reflectionQuestion?: string,
  relatedHolidayKey?: string,
): DailyLearningContent {
  return {
    id: `learning-cycle30-${String(sequence).padStart(2, '0')}`,
    moduleId: MODULE_ID,
    sequence,
    type,
    titleHebrew: 'לימוד יומי',
    topicHebrew,
    bodyHebrew,
    source: { sourceTitle, sourceReference },
    sourceHebrew: `${sourceTitle} ${sourceReference}`,
    estimatedMinutes: 3,
    reflectionQuestion,
    relatedHolidayKey,
    version: '1.0.0',
    status: 'published',
    readMoreLabel: 'להמשיך ללמוד',
  };
}

